/*
 * platform.h — интерфейс платформенного слоя.
 *
 * Каждая платформа (терминал Linux, консоль Windows, DOS, браузер)
 * реализует эти несколько функций в своём файле plat_*.c.
 * Всё остальное (ядро, игровая логика) одинаково для всех платформ.
 */
#ifndef PLATFORM_H
#define PLATFORM_H

#include "engine.h"

/* Подготовить экран и клавиатуру. 0 — успех. */
int plat_init(void);

/* Вернуть терминал/экран в исходное состояние. */
void plat_quit(void);

/* Неблокирующее чтение клавиши: KEY_NONE, если ничего не нажато. */
int plat_key(void);

/* Монотонное время в миллисекундах. */
unsigned long plat_ticks(void);

/* Пауза (на платформах с собственным циклом, как Web, не нужна). */
void plat_sleep(int ms);

/* Вывести экранный буфер 80x25 на реальный экран. */
void plat_present(const Screen *s);

#endif
